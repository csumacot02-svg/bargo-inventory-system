<?php

namespace App\Services;

use App\Models\InventoryItem;
use App\Models\InventoryRequest;
use App\Models\StockIn;
use App\Models\StockMovement;
use Illuminate\Http\Client\ConnectionException;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use Throwable;

class DeepSeekTrendAnalyzer
{
    private const CACHE_KEY = 'bargo.ai.deepseek.analysis';

    /**
     * @return array<string, mixed>
     */
    public function analyze(bool $force = false): array
    {
        $payload = $this->buildInventorySnapshot();
        $fingerprint = $this->snapshotFingerprint($payload);

        if (! $force) {
            $cached = $this->cachedAnalysisFor($fingerprint);
            if ($cached !== null) {
                return $cached;
            }
        }

        $apiKey = trim((string) config('services.deepseek.key'));

        if ($apiKey === '') {
            return $this->fallback(
                $payload,
                'DeepSeek API key not set. Showing built-in rule-based analysis. Add DEEPSEEK_API_KEY in .env to enable AI.'
            );
        }

        $baseUrl = rtrim((string) config('services.deepseek.base_url', 'https://api.deepseek.com'), '/');
        $endpoint = $baseUrl.'/chat/completions';
        $model = (string) config('services.deepseek.model', 'deepseek-v4-flash');

        try {
            $response = Http::timeout(90)
                ->acceptJson()
                ->asJson()
                ->withToken($apiKey)
                ->post($endpoint, [
                    'model' => $model,
                    'messages' => [
                        [
                            'role' => 'system',
                            'content' => 'BARGO inventory advisor (SLSU-Hinunangan). Reply with one JSON object only—no markdown, no prose outside JSON. '
                                .'Use only item names present in DATA. Never invent items, prices, or financial statements.',
                        ],
                        [
                            'role' => 'user',
                            'content' => $this->buildPrompt($payload),
                        ],
                    ],
                    'temperature' => 0.1,
                    'max_tokens' => 1200,
                    'stream' => false,
                    'thinking' => ['type' => 'disabled'],
                    'response_format' => ['type' => 'json_object'],
                ]);
        } catch (ConnectionException $e) {
            Log::warning('DeepSeek connection failed.', ['error' => $e->getMessage()]);

            return $this->fallback(
                $payload,
                'Could not reach the DeepSeek API. Check internet access, then try again. Showing rule-based analysis instead.'
            );
        } catch (Throwable $e) {
            Log::warning('DeepSeek request threw an exception.', ['error' => $e->getMessage()]);

            return $this->fallback(
                $payload,
                'DeepSeek request failed. Showing rule-based analysis instead.'
            );
        }

        if (! $response->successful()) {
            $reason = $this->describeApiFailure($response->status(), $response->json());

            Log::warning('DeepSeek request unsuccessful.', [
                'status' => $response->status(),
                'reason' => $reason,
            ]);

            return $this->fallback($payload, $reason, $response->json());
        }

        $content = data_get($response->json(), 'choices.0.message.content')
            ?: data_get($response->json(), 'choices.0.message.reasoning_content', '');

        if (trim((string) $content) === '') {
            return $this->fallback(
                $payload,
                'DeepSeek returned an empty analysis. Showing rule-based analysis instead.',
                $response->json()
            );
        }

        $parsed = $this->parseStructuredAnalysis((string) $content, $payload);

        $analysis = [
            'source' => 'deepseek',
            'summary' => $parsed['summary'],
            'recommendations' => $parsed['recommendations'],
            'predictions' => $parsed['predictions'],
            'raw' => $content,
            'cached' => false,
            'fingerprint' => $fingerprint,
            'analyzed_at' => now()->toDateTimeString(),
            'message' => 'Analysis and 30-day forecast generated by DeepSeek.',
        ];

        $this->storeCache($fingerprint, $analysis);

        return $analysis;
    }

    /**
     * Latest cached analysis for the current inventory fingerprint, if still valid.
     *
     * @return array<string, mixed>|null
     */
    public function cachedAnalysis(): ?array
    {
        $payload = $this->buildInventorySnapshot();

        return $this->cachedAnalysisFor($this->snapshotFingerprint($payload));
    }

    /**
     * @return array<string, mixed>|null
     */
    private function cachedAnalysisFor(string $fingerprint): ?array
    {
        $entry = Cache::get(self::CACHE_KEY);

        if (! is_array($entry) || ($entry['fingerprint'] ?? null) !== $fingerprint) {
            return null;
        }

        $analysis = $entry['analysis'] ?? null;
        if (! is_array($analysis) || ($analysis['source'] ?? '') !== 'deepseek') {
            return null;
        }

        $analysis['cached'] = true;
        $analysis['message'] = 'Showing cached DeepSeek analysis (no new API credits used). Force a new analysis if stock changed or you want a fresh forecast.';

        return $analysis;
    }

    /**
     * @param  array<string, mixed>  $analysis
     */
    private function storeCache(string $fingerprint, array $analysis): void
    {
        $minutes = max(5, (int) config('services.deepseek.cache_minutes', 60));

        Cache::put(self::CACHE_KEY, [
            'fingerprint' => $fingerprint,
            'analysis' => $analysis,
            'stored_at' => now()->toDateTimeString(),
        ], now()->addMinutes($minutes));
    }

    /**
     * Stable hash of inventory state (ignores wall-clock as_of).
     *
     * @param  array<string, mixed>  $payload
     */
    private function snapshotFingerprint(array $payload): string
    {
        $forHash = [
            'totals' => $payload['totals'] ?? [],
            'low_stock_items' => $payload['low_stock_items'] ?? [],
            'frequent_stockouts' => $payload['frequent_stockouts'] ?? [],
            'forecast' => $payload['forecast'] ?? [],
            'perishable_watch' => $payload['perishable_watch'] ?? [],
            'request_breakdown' => $payload['request_breakdown'] ?? [],
        ];

        return hash('sha256', (string) json_encode($forHash));
    }

    public function cacheMinutes(): int
    {
        return max(5, (int) config('services.deepseek.cache_minutes', 60));
    }

    public function buildInventorySnapshot(): array
    {
        $items = InventoryItem::query()->with('category')->where('is_active', true)->get();

        $lowStock = $items->filter->isLowStock()->values();
        $perishable = $items->where('is_perishable', true)->values();
        $expiring = $items->filter(fn (InventoryItem $i) => $i->isExpiringSoon(30) || $i->isExpired())->values();

        $recentMoves = StockMovement::query()
            ->with('inventoryItem')
            ->latest()
            ->take(40)
            ->get()
            ->map(fn (StockMovement $m) => [
                'item' => $m->inventoryItem?->name,
                'type' => $m->type,
                'change' => (float) $m->quantity_change,
                'after' => (float) $m->quantity_after,
                'at' => optional($m->created_at)->toDateTimeString(),
            ]);

        $requests = InventoryRequest::query()
            ->selectRaw('status, payment_type, payment_status, count(*) as total')
            ->groupBy('status', 'payment_type', 'payment_status')
            ->get();

        $stockInsMonth = StockIn::query()
            ->whereMonth('received_date', now()->month)
            ->whereYear('received_date', now()->year)
            ->count();

        $frequentStockouts = $this->frequentStockouts();
        $forecast = $this->ruleBasedForecast($items);

        $lowStockItems = $lowStock->sortBy('quantity_on_hand')->take(12)->values()->map(fn (InventoryItem $i) => [
            'name' => $i->name,
            'qty' => (float) $i->quantity_on_hand,
            'reorder' => (float) $i->reorder_level,
            'perishable' => $i->is_perishable,
            'expires' => optional($i->expiration_date)->toDateString(),
        ])->all();

        return [
            'as_of' => now()->toDateTimeString(),
            'totals' => [
                'active_items' => $items->count(),
                'low_stock' => $lowStock->count(),
                'perishable_items' => $perishable->count(),
                'expiring_or_expired' => $expiring->count(),
                'stock_ins_this_month' => $stockInsMonth,
            ],
            'low_stock_items' => $lowStockItems,
            'frequent_stockouts' => $frequentStockouts,
            'forecast' => $forecast,
            'perishable_watch' => $expiring->take(15)->map(fn (InventoryItem $i) => [
                'name' => $i->name,
                'qty' => (float) $i->quantity_on_hand,
                'expires' => optional($i->expiration_date)->toDateString(),
                'status' => $i->perishableStatus(),
            ])->all(),
            'request_breakdown' => $requests->toArray(),
            'recent_movements' => $recentMoves->all(),
        ];
    }

    /**
     * @param  array<string, mixed>  $snapshot
     * @param  array<string, mixed>|null  $analysis
     * @return array<string, mixed>
     */
    public function buildCharts(array $snapshot, ?array $analysis = null): array
    {
        $low = collect($snapshot['low_stock_items'] ?? []);
        $stockouts = collect($snapshot['frequent_stockouts']['items'] ?? []);
        $useAnalysis = is_array($analysis) && ! empty($analysis['predictions']);
        $useDeepSeek = $useAnalysis && ($analysis['source'] ?? '') === 'deepseek';
        $forecast = collect($useAnalysis ? $analysis['predictions'] : ($snapshot['forecast'] ?? []));

        return [
            'low_stock' => [
                'labels' => $low->pluck('name')->all(),
                'on_hand' => $low->pluck('qty')->map(fn ($v) => (float) $v)->all(),
                'reorder' => $low->pluck('reorder')->map(fn ($v) => (float) $v)->all(),
            ],
            'stockouts' => [
                'mode' => $snapshot['frequent_stockouts']['mode'] ?? 'outflow',
                'labels' => $stockouts->pluck('name')->all(),
                'values' => $stockouts->pluck('value')->map(fn ($v) => (float) $v)->all(),
                'value_label' => $snapshot['frequent_stockouts']['value_label'] ?? 'Quantity issued',
            ],
            'forecast' => [
                'source' => $useDeepSeek ? 'deepseek' : 'rule_based',
                'labels' => $forecast->pluck('name')->all(),
                'values' => $forecast->pluck('forecast_30d_qty')->map(fn ($v) => (float) $v)->all(),
                'risks' => $forecast->pluck('stockout_risk')->all(),
            ],
        ];
    }

    /**
     * @return array{mode: string, value_label: string, items: list<array<string, mixed>>}
     */
    private function frequentStockouts(): array
    {
        $since = now()->subDays(90);

        $hits = StockMovement::query()
            ->join('inventory_items', 'inventory_items.id', '=', 'stock_movements.inventory_item_id')
            ->where('inventory_items.is_active', true)
            ->where('stock_movements.created_at', '>=', $since)
            ->where('stock_movements.quantity_change', '<', 0)
            ->where('stock_movements.quantity_after', '<=', 0)
            ->selectRaw('inventory_items.name as name, COUNT(*) as stockout_events')
            ->groupBy('stock_movements.inventory_item_id', 'inventory_items.name')
            ->orderByDesc('stockout_events')
            ->limit(12)
            ->get();

        if ($hits->isNotEmpty()) {
            return [
                'mode' => 'stockout_hits',
                'value_label' => 'Times stock hit zero (90 days)',
                'items' => $hits->map(fn ($row) => [
                    'name' => $row->name,
                    'value' => (int) $row->stockout_events,
                ])->all(),
            ];
        }

        $outflow = StockMovement::query()
            ->join('inventory_items', 'inventory_items.id', '=', 'stock_movements.inventory_item_id')
            ->where('inventory_items.is_active', true)
            ->where('stock_movements.created_at', '>=', $since)
            ->whereIn('stock_movements.type', ['release', 'payment_sale'])
            ->selectRaw('inventory_items.name as name, SUM(ABS(stock_movements.quantity_change)) as qty_out')
            ->groupBy('stock_movements.inventory_item_id', 'inventory_items.name')
            ->orderByDesc('qty_out')
            ->limit(12)
            ->get();

        return [
            'mode' => 'outflow',
            'value_label' => 'Quantity issued (90 days)',
            'items' => $outflow->map(fn ($row) => [
                'name' => $row->name,
                'value' => round((float) $row->qty_out, 2),
            ])->all(),
        ];
    }

    /**
     * @param  Collection<int, InventoryItem>  $items
     * @return list<array<string, mixed>>
     */
    private function ruleBasedForecast(Collection $items): array
    {
        $since = now()->subDays(90);
        $windowDays = 90;

        $outflow = StockMovement::query()
            ->where('created_at', '>=', $since)
            ->whereIn('type', ['release', 'payment_sale'])
            ->selectRaw('inventory_item_id, SUM(ABS(quantity_change)) as qty_out')
            ->groupBy('inventory_item_id')
            ->pluck('qty_out', 'inventory_item_id');

        return $items
            ->map(function (InventoryItem $item) use ($outflow, $windowDays) {
                $qtyOut = (float) ($outflow[$item->id] ?? 0);
                $avgDaily = $qtyOut / $windowDays;
                $forecast30 = round($avgDaily * 30, 2);
                $onHand = (float) $item->quantity_on_hand;
                $daysUntil = $avgDaily > 0 ? (int) floor($onHand / $avgDaily) : null;

                $risk = 'low';
                if ($item->isLowStock() && $avgDaily > 0) {
                    $risk = 'high';
                } elseif ($daysUntil !== null && $daysUntil <= 14) {
                    $risk = 'high';
                } elseif ($daysUntil !== null && $daysUntil <= 30) {
                    $risk = 'medium';
                } elseif ($item->isLowStock()) {
                    $risk = 'medium';
                }

                $note = $avgDaily <= 0
                    ? 'No outbound movement in 90 days.'
                    : 'Projected from 90-day average usage of '.round($avgDaily, 2).' per day.';

                return [
                    'name' => $item->name,
                    'forecast_30d_qty' => $forecast30,
                    'stockout_risk' => $risk,
                    'days_until_stockout' => $daysUntil,
                    'note' => $note,
                ];
            })
            ->filter(fn (array $row) => $row['forecast_30d_qty'] > 0 || in_array($row['stockout_risk'], ['high', 'medium'], true))
            ->sortByDesc('forecast_30d_qty')
            ->take(12)
            ->values()
            ->all();
    }

    private function fallback(array $payload, string $message, mixed $raw = null): array
    {
        return [
            'source' => 'rule_based_fallback',
            'summary' => $this->ruleBasedSummary($payload),
            'recommendations' => $this->ruleBasedRecommendations($payload),
            'predictions' => $payload['forecast'] ?? [],
            'raw' => $raw,
            'cached' => false,
            'analyzed_at' => now()->toDateTimeString(),
            'message' => $message,
        ];
    }

    /**
     * @param  array<string, mixed>  $payload
     * @return array{summary: string, recommendations: list<string>, predictions: list<array<string, mixed>>}
     */
    private function parseStructuredAnalysis(string $content, array $payload): array
    {
        $json = $this->extractJson($content);
        $fallbackForecast = $payload['forecast'] ?? [];

        if (! is_array($json)) {
            return [
                'summary' => $content,
                'recommendations' => [],
                'predictions' => $fallbackForecast,
            ];
        }

        $recommendations = array_values(array_filter(array_map(
            fn ($row) => is_string($row) ? trim($row) : '',
            (array) ($json['recommendations'] ?? [])
        )));
        $recommendations = array_slice($recommendations, 0, 4);

        $predictions = $this->normalizePredictions((array) ($json['predictions'] ?? []));
        $predictions = array_slice($predictions, 0, 8);

        return [
            'summary' => trim((string) ($json['summary'] ?? $content)),
            'recommendations' => $recommendations,
            'predictions' => $predictions !== [] ? $predictions : $fallbackForecast,
        ];
    }

    /**
     * @param  list<mixed>  $predictions
     * @return list<array<string, mixed>>
     */
    private function normalizePredictions(array $predictions): array
    {
        $normalized = [];

        foreach ($predictions as $row) {
            if (! is_array($row)) {
                continue;
            }

            $name = trim((string) ($row['name'] ?? $row['item'] ?? ''));
            if ($name === '') {
                continue;
            }

            $risk = strtolower((string) ($row['stockout_risk'] ?? $row['risk'] ?? 'medium'));
            if (! in_array($risk, ['high', 'medium', 'low'], true)) {
                $risk = 'medium';
            }

            $normalized[] = [
                'name' => $name,
                'forecast_30d_qty' => round((float) ($row['forecast_30d_qty'] ?? $row['forecast'] ?? 0), 2),
                'stockout_risk' => $risk,
                'days_until_stockout' => isset($row['days_until_stockout']) ? (int) $row['days_until_stockout'] : null,
                'note' => trim((string) ($row['note'] ?? '')),
            ];
        }

        return array_slice($normalized, 0, 12);
    }

    private function extractJson(string $content): mixed
    {
        $trimmed = trim($content);

        if (preg_match('/```(?:json)?\s*(\{.*\})\s*```/s', $trimmed, $matches) === 1) {
            $trimmed = $matches[1];
        }

        $decoded = json_decode($trimmed, true);
        if (is_array($decoded)) {
            return $decoded;
        }

        $start = strpos($trimmed, '{');
        $end = strrpos($trimmed, '}');
        if ($start === false || $end === false || $end <= $start) {
            return null;
        }

        $decoded = json_decode(substr($trimmed, $start, $end - $start + 1), true);

        return is_array($decoded) ? $decoded : null;
    }

    private function describeApiFailure(int $status, mixed $json): string
    {
        $apiMessage = strtolower((string) data_get($json, 'error.message', ''));

        if ($status === 402 || str_contains($apiMessage, 'insufficient balance')) {
            return 'DeepSeek account has no credits (Insufficient Balance). Top up at https://platform.deepseek.com, then run analysis again.';
        }

        if ($status === 401 || str_contains($apiMessage, 'authentication') || str_contains($apiMessage, 'invalid api')) {
            return 'DeepSeek rejected the API key. Check DEEPSEEK_API_KEY in .env, then run php artisan config:clear.';
        }

        if ($status === 429) {
            return 'DeepSeek rate limit reached. Wait a moment, then try again. Showing rule-based analysis instead.';
        }

        if ($status === 400 && (str_contains($apiMessage, 'model') || str_contains($apiMessage, 'not found'))) {
            return 'DeepSeek model is invalid. Set DEEPSEEK_MODEL=deepseek-v4-flash in .env, then run php artisan config:clear.';
        }

        return 'DeepSeek request failed (HTTP '.$status.'). Showing rule-based analysis instead.';
    }

    private function buildPrompt(array $payload): string
    {
        $compact = [
            'totals' => $payload['totals'],
            'low_stock' => $payload['low_stock_items'],
            'stockouts' => $payload['frequent_stockouts'],
            'baseline_forecast' => array_map(static fn (array $row) => [
                'name' => $row['name'],
                'forecast_30d_qty' => $row['forecast_30d_qty'],
                'stockout_risk' => $row['stockout_risk'],
                'days_until_stockout' => $row['days_until_stockout'],
            ], array_slice($payload['forecast'] ?? [], 0, 8)),
            'perishable' => $payload['perishable_watch'],
        ];

        return 'Task: prioritize BARGO restocking for the next 30 days.'."\n"
            .'Return JSON only with keys: summary (string, max 3 sentences),'
            .' recommendations (array of up to 4 short actions),'
            .' predictions (array of up to 8 objects: name, forecast_30d_qty, stockout_risk high|medium|low, days_until_stockout, note).'."\n"
            .'Rules: use only names in DATA; prefer low_stock, stockouts, and baseline_forecast;'
            .' forecast_30d_qty = expected outbound qty in 30 days; keep recommendations specific and actionable.'."\n"
            .'DATA:'.json_encode($compact, JSON_UNESCAPED_UNICODE);
    }

    private function ruleBasedSummary(array $payload): string
    {
        $t = $payload['totals'];
        $topOut = collect($payload['frequent_stockouts']['items'] ?? [])->pluck('name')->take(3)->implode(', ');
        $topForecast = collect($payload['forecast'] ?? [])->pluck('name')->take(3)->implode(', ');

        $summary = "As of {$payload['as_of']}: {$t['active_items']} active items, "
            ."{$t['low_stock']} below reorder, {$t['perishable_items']} perishable SKUs, "
            ."{$t['expiring_or_expired']} expiring/expired, and {$t['stock_ins_this_month']} stock-ins this month. ";

        if ($topOut !== '') {
            $summary .= "Most frequent stock-out / issued items (90 days): {$topOut}. ";
        }

        if ($topForecast !== '') {
            $summary .= "Highest 30-day usage outlook: {$topForecast}. ";
        }

        return $summary.'Stock quantities update automatically on successful stock-in, item release, and confirmed payment transactions.';
    }

    private function ruleBasedRecommendations(array $payload): array
    {
        $recs = [];

        foreach (array_slice($payload['low_stock_items'], 0, 5) as $item) {
            $recs[] = "Replenish {$item['name']} (qty {$item['qty']} ≤ reorder {$item['reorder']}).";
        }

        foreach (array_slice($payload['forecast'] ?? [], 0, 3) as $item) {
            if (($item['stockout_risk'] ?? '') === 'high') {
                $recs[] = "Watch {$item['name']}: 30-day forecast {$item['forecast_30d_qty']} units"
                    .(isset($item['days_until_stockout']) ? ", about {$item['days_until_stockout']} days of cover." : '.');
            }
        }

        foreach (array_slice($payload['perishable_watch'], 0, 3) as $item) {
            $recs[] = "Perishable watch: {$item['name']} — {$item['status']} (expires {$item['expires']}). Use FIFO and avoid issuing expired stock.";
        }

        if ($recs === []) {
            $recs[] = 'No critical low-stock or perishable risks detected. Continue routine monitoring.';
        }

        return array_values(array_unique($recs));
    }
}
